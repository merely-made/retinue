//! Linkboy: the firmware and link-update tool of the retinue family.
//!
//! A linkboy carried the light that saw travellers through dark streets; this one carries
//! firmware over the link. It is the friendly face of the stock-hardware, user-flash
//! posture: the tool a person runs once, nervously, to put a retinue image on a board they
//! own — and later, the lane by which a board already in the field takes an update.
//!
//! # Status
//!
//! Founding stub. The name is claimed and the role is decided. The bench today flashes over
//! serial DFU (`adafruit-nrfutil`) and `espflash`; this tool arrives by wrapping those
//! paths behind one door. See the retinue repository's design docs.
