//! Postilion: the shared radio-host library of the retinue family.
//!
//! A postilion rides mounted on the lead horse, guiding the team from inside the motive
//! apparatus — read against [`outrider`](https://crates.io/crates/outrider), who escorts
//! from alongside. This crate is that riding position: the host-side logic every
//! radio-driving application embeds — identities, peer tables, radio session handling,
//! delivery — extracted from the first consumer that revealed its shape.
//!
//! # Status
//!
//! Founding stub. The name is claimed and the role is decided; the code arrives as the
//! `park` example's guts move out of `outrider` and under the `signalman` application.
//! See the retinue repository's design docs.
